-- ================================================================ lazy data load (same convention
-- periodic.lua's loadIsotopeData uses for its own generated data file)
local function loadPhysmatData()
  if PM.data then return PM.data end
  local candidates = {
    "../scripts/lua/rpg_plugins/physmat_data.lua",
    "scripts/lua/rpg_plugins/physmat_data.lua",
    "D:/The-Powder-Toy/scripts/lua/rpg_plugins/physmat_data.lua",
    "D:/powder-toy/scripts/lua/rpg_plugins/physmat_data.lua",
  }
  for _, path in ipairs(candidates) do
    local f = io.open(path, "r")
    if f then
      f:close()
      local chunk, lerr = loadfile(path)
      if chunk then
        local ok, tbl = pcall(chunk)
        if ok and type(tbl) == "table" then
          PM.data = tbl
          PBX.log(TAG, string.format("physmat_data loaded from %s: %d fallSolids, %d gases, %d liquids",
            path, #(tbl.fallSolids or {}), #(tbl.gases or {}), #(tbl.liquids or {})))
          return tbl
        end
      else
        PBX.log(TAG, "physmat_data.lua load error at " .. path .. ": " .. tostring(lerr))
      end
    end
  end
  PBX.log(TAG, "physmat_data.lua not found on any candidate path -- run scripts/gen_physmat.py")
  return nil
end

-- ================================================================ #1/#2: live element-property fixes.
-- elem.property(id, "Update", fn) and elem.property(id, "Gravity", v) both hit
-- AssertMutableToolsEvent -> AssertInterfaceEvent in the engine (src/lua/LuaElements.cpp:591,
-- LuaScriptInterface.h:188) -- restricted to a real interface-event context, exactly the same
-- restriction class the menu bug (R.setTptMenus/tpt.num_menus) already hit and worked around.
-- A fresh boot's Autorun() DOES carry eventTraitInterface (confirmed: LuaScriptInterface.cpp:223
-- calls tpt_lua_pcall(..., eventTraitInterface) for autorun.lua), so the top-level calls below
-- succeed on a real fresh boot. A bridge-triggered hot reload (plain execute_lua, no event
-- traits -- confirmed via powder_bridge/client.py's own _execute_lua_interface docstring) does
-- NOT, so any failure here is queued and retried from R.hooks.tick -- a real TickEvent handler,
-- which DOES carry eventTraitInterface (same doc, "TickEvent{} traits DO include
-- eventTraitInterface") -- same pending/retry shape as R.applyPendingMenus().
-- Returns true ("handled, skip the engine's own post-Update continuation for this particle
-- this tick" -- the documented contract, bridge_src/20_behaviors.lua's own header, "only a Lua
-- boolean true means stop, do not fall through to the built-in update") whenever the particle
-- did NOT move this tick, so a landed block reaches the exact same `continue` early-exit a truly
-- static native solid takes. LIVE-VERIFIED THIS MATTERS, not a defensive guess: an earlier version
-- of this function always returned false, and a lab containment test (own isolated instance, this
-- commit's acceptance report) found a two-wall+floor vessel built from fall-enabled elements
-- visibly sinking (top of wall drifted 235->243 over several seconds) and leaking a poured WATR
-- particle through the wall once real water was introduced nearby -- while the identical shape
-- built from native BRCK (Update==nil, takes the engine's own early `continue`) held. Returning
-- true while stationary was the fix that made the periodic-element vessel hold exactly as well as
-- the native-BRCK control (see this commit's acceptance report for the before/after numbers).
local function fallUpdate(i, x, y, surround_space, nt)
  if PBX.cellFree(x, y + 1) then
    sim.partProperty(i, "y", y + 1)
    return false
  end
  return true
end

local function tryInstallFall(name)
  if PM.fallInstalled[name] then return true end
  local id = eid(name)
  if not id then
    -- Not resolvable yet -- either this custom element's deferred allocation job hasn't
    -- completed (bridge_src/10_registry.lua's own documented window between a define being
    -- accepted and its id existing) or this hot-reload landed before the periodic seed's own
    -- registration pass ran. Either way, queue and let the tick hook keep trying rather than
    -- silently giving up -- LIVE-VERIFIED this path is real and non-trivial in size: a lab
    -- boot found 62/80 fallSolids and 2/7 gases still unresolved at the moment this plugin's
    -- own reload ran (see this commit's acceptance report).
    PM.fallPending[name] = true
    return false
  end
  local ok = pcall(elem.property, id, "Update", fallUpdate)
  if ok then
    PM.fallInstalled[name] = true
    PM.fallPending[name] = nil
    return true
  end
  PM.fallPending[name] = true
  return false
end

local GAS_BUOYANCY = -0.12
local function tryFixGasGravity(name)
  if PM.gasFixed[name] then return true end
  local id = eid(name)
  if not id then
    PM.gasPending[name] = true   -- same deferred-allocation race as tryInstallFall -- retry later
    return false
  end
  local okRead, current = pcall(elem.property, id, "Gravity")
  if okRead and current and current ~= 0 then
    -- Seed already carries a real non-zero gravity for this element (a future regeneration
    -- might set one) -- leave it alone, don't overwrite a real value with the fallback.
    PM.gasFixed[name] = true
    PM.gasPending[name] = nil
    return true
  end
  local ok = pcall(elem.property, id, "Gravity", GAS_BUOYANCY)
  if ok then
    PM.gasFixed[name] = true
    PM.gasPending[name] = nil
    return true
  end
  PM.gasPending[name] = true
  return false
end

local function installAllFall()
  local data = loadPhysmatData(); if not data then return end
  for _, name in ipairs(data.fallSolids or {}) do tryInstallFall(name) end
  for _, name in ipairs(data.zeroGravityGases or {}) do tryFixGasGravity(name) end
end

local function retryPending()
  local any = false
  for name in pairs(PM.fallPending) do any = true; tryInstallFall(name) end
  for name in pairs(PM.gasPending) do any = true; tryFixGasGravity(name) end
  return any
end

