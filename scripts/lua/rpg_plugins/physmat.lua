  -- Bounded: fallPending/gasPending only ever hold entries that failed an interface-event-gated
  -- call this session (at most 80 + 7 total, per physmat_data.lua) -- not a per-frame scan over
  -- particles. Once every name installs (normally the very first tick after a fresh boot, since
  -- Autorun already carries eventTraitInterface -- see #1/#2 above) both tables are empty and
  -- this is two empty `pairs()` iterations, i.e. free.
  retryPending()
end)

