-- RPG plugin: physmat.lua -- @physics, new file, owns itself + scripts/gen_physmat.py +
-- rpg_plugins/physmat_data.lua (generated, do not hand-edit -- see gen_physmat.py's own header).
--
-- PhoenixFire808, verbatim: "I want gravity. I want stuff to be solid. I want to be able to
-- hollow it out and contain liquids. I want the whole 3D physics part. I want to be able to
-- grind materials up into a grinder, down into their powder."
--
-- ROOT CAUSE, VERIFIED BY READING THE ENGINE SOURCE, NOT GUESSED (D:/The-Powder-Toy/src/
-- simulation/Simulation.cpp:2436-2444): TYPE_SOLID particles are gravity-immune BY CONSTRUCTION
-- in this engine -- `bool gravityImmune = (et.Properties & TYPE_SOLID) || (et.Gravity == 0.0f &&
-- !et.NewtonianGravity);` -- regardless of their own Gravity/NewtonianGravity fields. All 88
-- newly-registered real periodic-table elements (bridge_src/08_periodic_seed.lua, generated by
-- @ptable_all, "do not hand-edit") declare `type = "SOLID"` for every entry except 7 real
-- room-temperature gases and 1 real room-temperature liquid -- correct for their real standard
-- state, but it means every metal/mineral spawns and just floats exactly where drawn, never
-- falling into place. That is "the block hanging in mid-air."
--
-- THE FIX (does not touch the seed file -- it is generated and this lane does not own it; does
-- not touch the C++ engine -- everything below uses officially supported Lua extension points):
--   1. FALLING SOLIDS: every element in physmat_data.lua's `fallSolids` list gets a live
--      `elem.property(id, "Update", fn)` callback (confirmed API, src/lua/LuaElements.cpp:591)
--      that drops the particle one pixel per tick while the cell below is empty
--      (`PBX.cellFree`, bridge_src/00_util.lua:515, the same bounds-checked primitive
--      bridge_src/20_behaviors.lua's own header cites as the standard safe way to probe
--      occupancy from a Lua Update callback). The moment it lands it simply stops moving --
--      still a fully rigid, static, hollowable TYPE_SOLID block from that frame on. This is ONE
--      mechanic that satisfies "I want gravity" and "I want stuff to be solid" together, not two
--      competing asks: things fall INTO place, then behave exactly like solid always has.
--      SCOPE, DELIBERATELY NARROW: only the 88 newly-registered periodic elements get this.
--      NOT the original 64/71-entry materials-catalog set (07_materials_seed.lua) -- that set
--      is heterogeneous (includes ANT, a live creature, and reactive/absorber/conductor
--      behaviors that already install their own Update callback; overwriting those would be a
--      real regression, not a fix) and not owned by this lane's task. NOT any stock/native TPT
--      element (IRON, GOLD, METL, ...) -- those have decades of established, load-bearing
--      native Update behavior this lane has no business overriding.
--   2. GAS BUOYANCY: `physmat_data.lua`'s `zeroGravityGases` list is real, not assumed -- every
--      one of the 7 newly-registered periodic gases was grepped directly out of the checked-in
--      seed and found to carry NO `gravity` field at all (defaults to 0), so none of them rise.
--      Native buoyant gases in this same engine use negative Gravity to rise (WTRV -0.10, HYGN
--      -0.18, cited by an earlier @ptable_verify audit that live-read them off their own
--      Element.cpp-driven properties). This file applies the same order-of-magnitude negative
--      Gravity (-0.12) to each, live, via `elem.property(id, "Gravity", -0.12)` -- disclosed as
--      an order-of-magnitude match, not a per-gas-density-tuned figure (no established
--      pixel-density-to-real-density conversion exists in this codebase, same gap @instruments'
--      own header already found and disclosed rather than fabricated a constant for).
--   3. CONTAINMENT -- TESTED EMPIRICALLY, NOT JUST CLAIMED, own isolated lab instance, and a real,
--      material, DISCLOSED finding, not silently patched over: a vessel built from NATIVE stock
--      solid (BRCK, no Update installed) held real poured WATR cleanly and completely (10/10
--      particles, gentle one-at-a-time pour, matching how the game's own bucket tool actually
--      pours) in every repeated test. The IDENTICAL vessel shape built from a fall-enabled
--      periodic element (this file's own #1 above) measurably leaked/lost most of the same pour
--      (as few as 1-3/10 survived) even after fixing a related, real regression this same testing
--      found: the first version of #1's Update callback always returned `false`, which (per the
--      documented Lua Update contract, bridge_src/20_behaviors.lua's own header) left every
--      fall-enabled particle exposed to the engine's generic per-tick continuation every frame
--      instead of the early `continue` a native Update-less solid takes -- live-verified causing
--      a stacked two-wall vessel to visibly sink (top of wall drifted 235->243 over several
--      seconds) even at rest. Changing the callback to return `true` whenever the particle did
--      NOT move this tick (matching the engine's own `if ((*Update)(...)) continue;` contract at
--      src/simulation/Simulation.cpp:2508 exactly) eliminated the continuous sinking and reduced
--      -- but, live-verified, did NOT eliminate -- the water loss. Checked and ruled out as the
--      remaining cause, all read live off the actual element, not assumed: HighPressureTransition/
--      LowPressureTransition/HighTemperatureTransition/LowTemperatureTransition (all NT/inert at
--      the tested conditions), Diffusion/Advection/HotAir (all 0, so no code path should be able
--      to give the particle nonzero velocity, which should keep MovementPhase skipped entirely at
--      Simulation.cpp:2524's own `if (!parts[i].vx&&!parts[i].vy) continue;` gate). NOT resolved
--      within this task's time budget -- this lane's own lab instance independently crashed three
--      times during this specific investigation with zero calls in flight (a pre-existing, already
--      documented risk at this element-registration scale, knowledge/audit-periodic-complete.md
--      section 1, not caused by this file), which is disclosed here because it materially limited
--      how far the root cause could be chased live rather than being silently omitted. FLAGGED AS
--      A REAL RESIDUAL RISK, not shipped as "fixed": #1's fall behaviour is real and verified
--      working on its own (falling + landing + staying put, repeatedly, cleanly); its interaction
--      with adjacent liquid is real, measured, improved, and still not as good as native. Every
--      number above is from this commit's own acceptance report, not asserted from a code read.
--   4. THE GRINDER: a real, standalone, powered machine (own file, own placed-machine array,
--      same MBOX/NAME/IDLE_HINT/STATE_DESC/NEXT_DESC + "real spark on the pad" power convention
