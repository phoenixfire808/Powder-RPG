-- ================================================================ #4: the Grinder
local pwcrIdCache
local function pwcrId() if pwcrIdCache == nil then pwcrIdCache = eid("PWCR") or false end; return pwcrIdCache or nil end

local function isSolidType(t)
  if not t or t == 0 then return false end
  local ok, props = pcall(elem.property, t, "Properties")
  if not ok or not props then return false end
  return bit.band(props, elem.TYPE_SOLID) ~= 0
end

local BASE_GRIND_TICKS = 60   -- 1s floor even for the softest material at 60 ticks/s
local function grindTicksFor(t)
  local ok, hardness = pcall(elem.property, t, "Hardness")
  hardness = (ok and hardness) or 35   -- 35 matches this codebase's own typical custom-material default
  return BASE_GRIND_TICKS + math.floor(hardness * 3)   -- hardness 5 -> ~75 ticks (1.25s), 100 -> 360 ticks (6s)
end

local NAME, MBOX, IDLE_HINT, STATE_DESC, NEXT_DESC = {}, {}, {}, {}, {}
NAME.grinder = "Grinder"
MBOX.grinder = { 0, -5, 8 }
IDLE_HINT.grinder = "Power the pad, drop any real solid into the hopper slot"
STATE_DESC.grinder = function(m)
  if not poweredAt(m.pad.x, m.pad.y, 1) then return "unpowered" end
  return m.grindType and "grinding" or "idle (powered)"
end
NEXT_DESC.grinder = function(m)
  if not poweredAt(m.pad.x, m.pad.y, 1) then return "Touch a sparked " .. nice(WMAT) .. " wire to the pad" end
  local p = partAt(m.slot.x, m.slot.y)
  local t = p and sim.partProperty(p, "type")
  if not t or t == 0 then return "Drop any real solid material into the hopper slot" end
  if not isSolidType(t) then return (nameOf(t) or "?") .. " isn't a solid -- the grinder only mills solid material" end
  local need = grindTicksFor(t)
  return string.format("Grinding %s: %d/%d -- harder material grinds slower", nameOf(t) or "?", m.grindProgress or 0, need)
end

local function buildGrinder(mx, my)
  local wx, wy = mx + R.cam.x, my + R.cam.y; local gy = groundY(wx, wy)
  -- hopper funnel over a grinding wheel, STEEL housing, open chute at the base so real PWCR
  -- output falls out under its own (native, TYPE_PART) gravity to a basin the player can mine
  boxFill(wx - 3, gy - 7, wx + 3, gy - 1, STEELMAT)
  clearBox(wx - 2, gy - 6, wx + 2, gy - 5)   -- hopper mouth, open top
  clearBox(wx - 1, gy - 4, wx + 1, gy - 2)   -- grinding chamber
  setAt(wx, gy - 3, "PSCN")                  -- wheel hub, cosmetic "spinning" marker
  clearBox(wx - 1, gy - 1, wx + 1, gy - 1)   -- chute out the bottom into the basin
  boxFill(wx - 2, gy + 1, wx + 2, gy + 2, "GLAS")   -- sight basin, output collects here
  clearBox(wx - 1, gy + 1, wx + 1, gy + 1)
  setAt(wx - 3, gy - 4, "PSCN")              -- power pad on the housing side
  R.physmatM[#R.physmatM + 1] = { kind = "grinder", x = wx, y = gy,
    slot = { x = wx, y = gy - 5 }, pad = { x = wx - 3, y = gy - 4 }, basin = { x = wx, y = gy + 1 },
    angle = 0, grindType = nil, grindProgress = 0 }
  say("Grinder placed - power the pad and drop any real solid into the hopper slot")
end

local function updateGrinder()
  local pid = pwcrId()
  for _, m in ipairs(R.physmatM) do if m.kind == "grinder" then
    local on = poweredAt(m.pad.x, m.pad.y, 1)
    if on then m.angle = (m.angle or 0) + 0.5 end
    local p = partAt(m.slot.x, m.slot.y)
    local t = p and sim.partProperty(p, "type")
    if on and p and t and t ~= 0 and isSolidType(t) and pid then
      if m.grindType ~= t then m.grindType = t; m.grindProgress = 0 end
      m.grindProgress = (m.grindProgress or 0) + 1
      local need = grindTicksFor(t)
      if m.grindProgress >= need then
        sim.partProperty(p, "type", pid)
        sim.partProperty(p, "ctype", t)
        say("Ground into " .. (R.typeLabel and R.typeLabel(pid, t) or "Powder"))
        if R.tlog then R.tlog("info", "physmat", "grind complete", { src = nameOf(t), ticks = need }) end
        m.grindType = nil; m.grindProgress = 0
      end
    else
      m.grindType = nil; m.grindProgress = 0
    end
  end end
end

-- ================================================================ interaction: proximity prompt + panel
local function machineCentre(m)
  local b = MBOX[m.kind]
  if b then return m.x + b[1], m.y + b[2], b[3] end
  return m.x, m.y - 3, 8
end
local function machineAt(wx, wy)
  local best, bestD
  for _, m in ipairs(R.physmatM) do
    if MBOX[m.kind] then
      local cx, cy, r = machineCentre(m)
      local d = (wx - cx) * (wx - cx) + (wy - cy) * (wy - cy)
      if d <= r * r and (not bestD or d < bestD) then bestD = d; best = m end
    end
  end
  return best
end

